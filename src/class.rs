impl<'js, C: JsClass<'js> + 'js> IntoJs<'js> for Class<'js, C> {
    fn into_js(self, _ctx: &Ctx<'js>) -> Result<Value<'js>> {
        Ok(self.into_value())
    }
}

impl<'js, C: JsClass<'js> + 'js> FromJs<'js> for Class<'js, C> {
    fn from_js(_ctx: &Ctx<'js>, value: Value<'js>) -> Result<Self> {
        let type_name = value.type_name();
        Class::from_value(value).ok_or_else(|| Error::new_from_js(type_name, C::NAME))
    }
}

impl<'js> Object<'js> {
    /// Convert into a class handle if this object is an instance of `C`.
    pub fn into_class<C: JsClass<'js> + 'js>(self) -> core::result::Result<Class<'js, C>, Self> {
        if instance_cell::<C>(&self).is_some() { Ok(Class(self, PhantomData)) } else { Err(self) }
    }

    pub fn as_class<C: JsClass<'js> + 'js>(&self) -> Option<&Class<'js, C>> {
        // SAFETY: `Class` is `(Object, PhantomData)`, layout-identical to `Object`.
        instance_cell::<C>(self).is_some().then(|| unsafe { &*(self as *const Object<'js> as *const Class<'js, C>) })
    }

    pub fn instance_of<C: JsClass<'js> + 'js>(&self) -> bool {
        instance_cell::<C>(self).is_some()
    }
}

/// Borrow the Rust instance behind `this` in a method implementation
/// (used by `#[rbun::methods]`).
pub fn with_instance<'js, C: JsClass<'js> + 'js, R>(this: &Value<'js>, f: impl FnOnce(&mut C) -> Result<R>) -> Result<R> {
    let ctx = *this.ctx();
    let object = this
        .as_object()
        .cloned()
        .ok_or_else(|| crate::Exception::throw_type(&ctx, &format!("expected `this` to be a {} instance", C::NAME)))?;
    let class = Class::<C>::from_object(object)
        .ok_or_else(|| crate::Exception::throw_type(&ctx, &format!("expected `this` to be a {} instance", C::NAME)))?;
    let cell = class.cell();
    let mut guard = cell.cell.try_borrow_mut().map_err(|_| Error::ClassBorrow(BorrowError::AlreadyBorrowed))?;
    f(&mut guard)
}

/// Builds the prototype for `#[rbun::methods]`: methods become functions on
/// the prototype object.
pub struct PrototypeBuilder<'js> {
    ctx: Ctx<'js>,
    prototype: Object<'js>,
}

impl<'js> PrototypeBuilder<'js> {
    pub fn new(ctx: &Ctx<'js>) -> Result<Self> {
        Ok(PrototypeBuilder { ctx: *ctx, prototype: Object::new(*ctx)? })
    }

    pub fn method<P, F>(self, name: &str, f: F) -> Result<Self>
    where
        F: crate::function::IntoJsFunc<'js, P> + 'js,
    {
        let function = crate::Function::new(self.ctx, f)?.with_name(name)?;
        self.prototype.set(name, function)?;
        Ok(self)
    }

    pub fn getter<P, F>(self, name: &str, f: F) -> Result<Self>
    where
        F: crate::function::IntoJsFunc<'js, P> + 'js,
    {
        self.prototype.prop(name, crate::object::Accessor::from(f).configurable().enumerable())?;
        Ok(self)
    }

    pub fn build(self) -> Object<'js> {
        self.prototype
    }
}
